// ============================================================
// スキーマ定義（db.py の SCHEMA_SQL をそのまま移植）
// 主キーはすべて意味を持たないサロゲートキー。標準コード（JIS 等）は
// ただの属性 + UNIQUE 制約として持つ。
// ============================================================

export const SCHEMA_SQL = `
-- 住所マスタ 3 テーブル
CREATE TABLE IF NOT EXISTS prefectures (
    id       integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    jis_code text NOT NULL UNIQUE,   -- JIS X 0401 2桁（先頭ゼロ保持のため text。例 '13'）
    name     text NOT NULL           -- 例 '東京都'
);

CREATE TABLE IF NOT EXISTS shikuchoson (
    id            integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    prefecture_id integer NOT NULL REFERENCES prefectures(id),
    jis_code      text NOT NULL UNIQUE,  -- JIS X 0402 5桁（例 '13106'）
    name          text NOT NULL          -- 例 '台東区'
);
CREATE INDEX IF NOT EXISTS idx_shikuchoson_pref ON shikuchoson (prefecture_id);

CREATE TABLE IF NOT EXISTS chibankuiki (
    -- 地番区域（大字町丁目）。地番はこの区域内で一意になる
    id             integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    shikuchoson_id integer NOT NULL REFERENCES shikuchoson(id),
    choaza_code    text NOT NULL,     -- 大字町丁目コード12桁の下6桁
    name           text NOT NULL,     -- 大字町丁目名（位置参照情報の表記そのまま。例 '下谷一丁目'）
    lat            double precision,  -- 代表点（位置参照情報由来）
    lng            double precision,
    UNIQUE (shikuchoson_id, choaza_code),
    UNIQUE (shikuchoson_id, name)
);
CREATE INDEX IF NOT EXISTS idx_chibankuiki_shikuchoson ON chibankuiki (shikuchoson_id);

CREATE TABLE IF NOT EXISTS parcels (
    id             integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    chibankuiki_id integer NOT NULL REFERENCES chibankuiki(id),  -- 地番区域マスタ参照（所在の正本）
    chiban         text NOT NULL,
    geometry       jsonb NOT NULL,    -- GeoJSON Polygon（[lng,lat]・末尾は始点の繰り返し）
    UNIQUE (chibankuiki_id, chiban)   -- 地番は地番区域内で一意
);
-- 2026-10 追加列: 筆の出所（master = 登記所備付地図データ由来 / manual = 案件の公図を下地に
-- ユーザーが描いた筆。Issue #44）。データに載っていない筆を運用で補うためのもので、
-- 手動の筆も (chibankuiki_id, chiban) で一意・土地からは同じく parcel_id で参照する
ALTER TABLE parcels ADD COLUMN IF NOT EXISTS source text NOT NULL DEFAULT 'master'
    CHECK (source IN ('master', 'manual'));

CREATE TABLE IF NOT EXISTS projects (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        text NOT NULL,
    description text NOT NULL DEFAULT '',
    polygon     jsonb,                     -- 案件領域 [[lat,lng], ...]
    address     text,
    access      text,
    staff       text,                      -- 担当者名
    current_bcr numeric,                   -- 現況建蔽率（%）
    current_far numeric,
    target_far  numeric,
    zoning      text,                      -- 用途地域（例「商業」）
    front_roads jsonb NOT NULL DEFAULT '[]',
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS lands (
    id          text PRIMARY KEY,
    project_id  integer NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
    parcel_id   integer NOT NULL REFERENCES parcels(id),
    description text NOT NULL DEFAULT '',
    area_m2     numeric NOT NULL DEFAULT 0,  -- 面積（㎡。登記の正本単位。坪は表示時に換算）
    status      text NOT NULL DEFAULT 'target' CHECK (status IN ('target', 'acquired')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    UNIQUE (project_id, parcel_id)
);
CREATE INDEX IF NOT EXISTS idx_lands_project ON lands (project_id, created_at);

CREATE TABLE IF NOT EXISTS land_owners (
    id        integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,  -- 追加順（= owners 配列の並び）
    land_id   text NOT NULL REFERENCES lands(id) ON DELETE CASCADE,
    name      text NOT NULL,
    share_num integer,
    share_den integer,
    address     text NOT NULL DEFAULT '',  -- 所有者住所
    reg_date    date,                      -- 登記日（未設定は NULL ↔ API では ''）
    reg_cause   text NOT NULL DEFAULT '',  -- 登記原因（相続/売買/遺贈 等）
    description text NOT NULL DEFAULT '',  -- 備考
    CHECK ((share_num IS NULL) = (share_den IS NULL)),
    CHECK (share_den IS NULL OR share_den > 0)
);
CREATE INDEX IF NOT EXISTS idx_land_owners_land ON land_owners (land_id, id);

-- 抵当権（土地の子。owners と同型の全置換・追加順保持）
CREATE TABLE IF NOT EXISTS land_mortgages (
    id      integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    land_id text NOT NULL REFERENCES lands(id) ON DELETE CASCADE,
    date    date,                          -- 設定日（未設定は NULL ↔ API では ''）
    amount  numeric,                       -- 債権額（万円）。未設定は NULL
    holder  text NOT NULL DEFAULT ''       -- 抵当権者
);
CREATE INDEX IF NOT EXISTS idx_land_mortgages_land ON land_mortgages (land_id, id);

-- 建物（土地の子。土地とは別に登記され所有者も異なりうる。更地は建物なし）
CREATE TABLE IF NOT EXISTS buildings (
    id           text PRIMARY KEY,
    land_id      text NOT NULL REFERENCES lands(id) ON DELETE CASCADE,
    location     text NOT NULL DEFAULT '',   -- 所在（登記上の所在。例「西浅草二丁目24番地3」）
    kaoku_number text NOT NULL DEFAULT '',   -- 家屋番号
    structure    text NOT NULL DEFAULT '',   -- 構造（例「木造2階建」）
    usage        text NOT NULL DEFAULT '',   -- 種類・用途（非予約語。静的 INSERT で使うため引用符不要）
    floor_area   numeric,                    -- 延床面積（㎡）。未設定は NULL
    built_date   date,                       -- 新築年月日（未設定は NULL ↔ API では ''）
    description  text NOT NULL DEFAULT '',   -- 備考
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_buildings_land ON buildings (land_id, created_at, id);
-- 2026-07 追加列（既存 DB をデータを保持したまま追随させる。CREATE TABLE IF NOT EXISTS は
-- 既存テーブルに列を足さないため、後から増えた列はここで冪等に ALTER する）
ALTER TABLE buildings ADD COLUMN IF NOT EXISTS location text NOT NULL DEFAULT '';
-- 2026-10 追加列: 居住者と建物の所有者の一致（match=一致 / mismatch=不一致 /
-- unknown=未確認）。既存の建物は DEFAULT により「未確認」になる
ALTER TABLE buildings ADD COLUMN IF NOT EXISTS resident_owner_match text NOT NULL DEFAULT 'unknown'
    CHECK (resident_owner_match IN ('match', 'mismatch', 'unknown'));

CREATE TABLE IF NOT EXISTS building_owners (
    id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,  -- 追加順（= owners 配列の並び）
    building_id text NOT NULL REFERENCES buildings(id) ON DELETE CASCADE,
    name        text NOT NULL,
    share_num   integer,
    share_den   integer,
    address     text NOT NULL DEFAULT '',    -- 所有者住所
    reg_date    date,                        -- 登記日（未設定は NULL ↔ API では ''）
    reg_cause   text NOT NULL DEFAULT '',    -- 登記原因（相続/売買/遺贈 等）
    description text NOT NULL DEFAULT '',    -- 備考
    CHECK ((share_num IS NULL) = (share_den IS NULL)),
    CHECK (share_den IS NULL OR share_den > 0)
);
CREATE INDEX IF NOT EXISTS idx_building_owners_building ON building_owners (building_id, id);
-- 2026-10: 持分を必須化（単独所有は 1/1）。旧フォームは「単独所有は空欄」だったため、
-- 所有者が 1 人だけの土地・建物で持分が空のものは 1/1 と同義として補完する（冪等）。
-- 複数所有者で持分が空のものは意味を決められないので触らない（編集時に入力を求める）
UPDATE land_owners o SET share_num = 1, share_den = 1
 WHERE o.share_num IS NULL
   AND (SELECT count(*) FROM land_owners x WHERE x.land_id = o.land_id) = 1;
UPDATE building_owners o SET share_num = 1, share_den = 1
 WHERE o.share_num IS NULL
   AND (SELECT count(*) FROM building_owners x WHERE x.building_id = o.building_id) = 1;

-- 抵当権（建物の子。land_mortgages と同型）
CREATE TABLE IF NOT EXISTS building_mortgages (
    id          integer GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    building_id text NOT NULL REFERENCES buildings(id) ON DELETE CASCADE,
    date        date,                        -- 設定日（未設定は NULL ↔ API では ''）
    amount      numeric,                     -- 債権額（万円）。未設定は NULL
    holder      text NOT NULL DEFAULT ''     -- 抵当権者
);
CREATE INDEX IF NOT EXISTS idx_building_mortgages_building ON building_mortgages (building_id, id);

-- 登記簿等の添付ファイル（登記事項証明書のスキャン PDF・画像）。
-- 土地・建物・案件のいずれか 1 つに紐づく（登記簿は土地と建物で別々に存在するため。
-- 案件に紐づくのは、筆を描く下地にする公図画像のみ＝Issue #44）。
-- バイト列は両アプリが共有する PostgreSQL に置く。ローカルでも Vercel でも
-- 追加のストレージ契約なしで動くことを優先した選択。将来 Vercel Blob へ移す場合は
-- data 列を blob_url 列に差し替え、queries/documents.ts だけを変更すればよい。
CREATE TABLE IF NOT EXISTS registry_documents (
    id           text PRIMARY KEY,
    land_id      text REFERENCES lands(id) ON DELETE CASCADE,      -- 土地の登記簿
    building_id  text REFERENCES buildings(id) ON DELETE CASCADE,  -- 建物の登記簿
    file_name    text NOT NULL,                  -- 元のファイル名（表示・ダウンロード名）
    content_type text NOT NULL,                  -- MIME タイプ（application/pdf 等）
    byte_size    integer NOT NULL,               -- バイト数（一覧表示用。data の長さと一致）
    data         bytea NOT NULL,                 -- ファイル本体
    uploaded_by  text NOT NULL DEFAULT '',       -- アップロードしたユーザーの表示名
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    project_id   integer REFERENCES projects(id) ON DELETE CASCADE,  -- 案件の公図（下地）
    overlay      jsonb,                          -- 案件の公図の地図上の位置合わせ（未設定は NULL）
    -- 土地・建物・案件のいずれか 1 つにだけ紐づくことを担保する
    CONSTRAINT registry_documents_owner_exactly_one
        CHECK (num_nonnulls(land_id, building_id, project_id) = 1)
);
CREATE INDEX IF NOT EXISTS idx_registry_documents_land
    ON registry_documents (land_id, created_at, id);
CREATE INDEX IF NOT EXISTS idx_registry_documents_building
    ON registry_documents (building_id, created_at, id);
-- 2026-10 追加列: 添付の種別（'registry' = 登記簿・'kouzu' = 公図）。既存行は登記簿扱い。
-- 公図は建物詳細の「公図」カードから添付する（Issue #42）
ALTER TABLE registry_documents ADD COLUMN IF NOT EXISTS kind text NOT NULL DEFAULT 'registry'
    CHECK (kind IN ('registry', 'kouzu'));
-- 2026-10 追加列: 案件に紐づく公図（筆を描く下地。Issue #44）と、その地図上の位置合わせ
-- （{center:[lat,lng], metersPerPixel, rotationDeg, opacity, imageWidth, imageHeight}）
ALTER TABLE registry_documents ADD COLUMN IF NOT EXISTS project_id integer
    REFERENCES projects(id) ON DELETE CASCADE;
ALTER TABLE registry_documents ADD COLUMN IF NOT EXISTS overlay jsonb;
CREATE INDEX IF NOT EXISTS idx_registry_documents_project
    ON registry_documents (project_id, created_at, id);
-- 建物に公図は無い（2026-10 廃止）。かつて建物に添付できた公図の行は消す（冪等。2 回目以降は 0 行）
DELETE FROM registry_documents WHERE building_id IS NOT NULL AND kind = 'kouzu';
-- 添付は紐づけ先ごと・種類ごとに 1 つまで（2026-10）。上限導入前に複数付いていた分は
-- 更新日時が最新の 1 つだけを残して消す（冪等。画面は 1 つしか表示しない）
DELETE FROM registry_documents WHERE id IN (
    SELECT id FROM (
        SELECT id, row_number() OVER (
            PARTITION BY land_id, building_id, project_id, kind
            ORDER BY updated_at DESC, created_at DESC, id DESC
        ) AS rn
        FROM registry_documents
    ) ranked WHERE rn > 1
);
-- 紐づけ先の制約を「土地か建物の一方」から「土地・建物・案件のいずれか 1 つ」へ差し替える
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'registry_documents_owner_one') THEN
        ALTER TABLE registry_documents DROP CONSTRAINT registry_documents_owner_one;
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'registry_documents_owner_exactly_one'
    ) THEN
        ALTER TABLE registry_documents ADD CONSTRAINT registry_documents_owner_exactly_one
            CHECK (num_nonnulls(land_id, building_id, project_id) = 1);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS visits (
    id            text PRIMARY KEY,
    land_id       text NOT NULL REFERENCES lands(id) ON DELETE CASCADE,
    user_name     text NOT NULL DEFAULT '',
    comment       text NOT NULL DEFAULT '',
    date          timestamptz NOT NULL DEFAULT now(),
    direct_or_tel text NOT NULL DEFAULT '',
    meeting_type  text NOT NULL DEFAULT '',
    next_date     timestamptz,             -- 未設定は NULL（API では '' に変換）
    progress      text NOT NULL DEFAULT '',
    principal     text NOT NULL DEFAULT 'principal'
);
CREATE INDEX IF NOT EXISTS idx_visits_land ON visits (land_id, date);

-- ユーザー（両システム共用のアカウント。営業=閲覧系 / 事務=入力系）
CREATE TABLE IF NOT EXISTS users (
    id            text PRIMARY KEY,                -- uuid（サロゲートキー。login_id は属性）
    login_id      text NOT NULL UNIQUE,            -- ログインID（半角英数と - _）
    name          text NOT NULL,                   -- 表示名
    role          text NOT NULL CHECK (role IN ('sales','office')),  -- sales=営業 / office=事務
    password_hash text NOT NULL,                   -- scrypt 形式（lib/auth/password.ts）。API には返さない
    is_active     boolean NOT NULL DEFAULT true,   -- 停止 = false（削除機能は持たない）
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now()
);

-- ログインセッション（両システム共用の認証基盤。lib/auth/session.ts）
-- 有効期限は持たない（無期限）。失効はログアウトによる行削除とアカウント停止のみ。
CREATE TABLE IF NOT EXISTS sessions (
    token      text PRIMARY KEY,   -- randomBytes(32) の base64url。推測不能なランダム値
    user_id    text NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sessions_user ON sessions (user_id);

CREATE TABLE IF NOT EXISTS app_meta (
    key   text PRIMARY KEY,
    value text NOT NULL
);
`;
